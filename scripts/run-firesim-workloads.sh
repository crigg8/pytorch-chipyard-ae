  cat <<'EOF'
Usage:
  bash scripts/run-firesim-workloads.sh [options]

Default:
  Run every FireSim workload generated by scripts/package-firemarshal-workload.sh,
  then preserve only model.log and autotune.log under
  scripts/figures/results-workload/<workload>/. FireSim/FireMarshal runtime
  files and logs are removed after the run, whether it succeeds or fails.

Options:
  --workload=NAME      Run/collect one workload. May be repeated or comma-separated.
  --preflight-only     Validate selected HWDB artifacts, then exit without a run.
  --resume             Skip workloads that already have both durable logs.
  --resume-from=NAME   Start from NAME in the
                       selected/discovered workload order.
  --rvv-panic-retries=N|unlimited
                       Retry an RVV workload after a detected kernel panic or
                       corrupt UART. Default: 0; unlimited must be explicit.
  -h, --help           Show this help.

Environment:
  PYTORCH_CHIPYARD_BITSTREAM_DIR             Bundled U250 runtime artifacts.
                                             Default: $WORKSPACE/bitstreams
  FIRESIM_HWDB_PATH                          Optional external HWDB override.
                                             By default a user-local HWDB
                                             is generated from the bundle.
  PYTORCH_CHIPYARD_FPGA_DB                   Default: /opt/firesim-db.json
  FIRESIM_RUNS_DIR                          Per-account FireSim run directory.
  PYTORCH_CHIPYARD_FIRESIM_RUNTIME_DIR      Generated config_runtime files.
  PYTORCH_CHIPYARD_RESULTS_WORKLOAD_DIR     FireSim results-workload directory.
  PYTORCH_CHIPYARD_FIGURE_RESULTS_WORKLOAD_DIR
                                             Collected result directory.
  PYTORCH_CHIPYARD_LOG_DIR                  Current stage2 log directory.
  PYTORCH_CHIPYARD_FIRESIM_PYTHON           Optional FireSim/HWDB Python
                                             override. Default:
                                             $CHIPYARD_DIR/.conda-env/bin/python3.
  PYTORCH_CHIPYARD_FIRESIM_RUN_FARM_HOST    Default: localhost
  PYTORCH_CHIPYARD_FIRESIM_RUN_FARM_SPEC    Default: one_fpgas_spec
  PYTORCH_CHIPYARD_CLEAN_FIRESIM_RUNS_DIR=0 Skip clearing FIRESIM_RUNS_DIR.
  PYTORCH_CHIPYARD_KEEP_RUNFARM=1           Skip terminaterunfarm.
  PYTORCH_CHIPYARD_FIRESIM_HW_CONFIG_OVERRIDES
                                             Comma-separated workload=hw_config list.

Failure handling:
  While runworkload is active, UART logs are monitored for guest failures such
