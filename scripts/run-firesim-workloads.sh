#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd -P)"
source "${SCRIPT_DIR}/env.sh"
source "${SCRIPT_DIR}/stage2-common.sh"

log() {
  printf '[firesim-run] %s\n' "$*"
}

warn() {
  printf '[firesim-run][warn] %s\n' "$*" >&2
}

die() {
  printf '[firesim-run][error] %s\n' "$*" >&2
  exit 1
}

