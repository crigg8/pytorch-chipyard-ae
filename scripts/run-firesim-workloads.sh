validate_name() {
  local label="$1"
  local value="$2"
  [[ "${value}" =~ ^[A-Za-z0-9._-]+$ ]] || \
    die "invalid ${label} '${value}'; use only letters, numbers, '.', '_', and '-'"
}

require_file() {
  local path="$1"
  [[ -f "${path}" ]] || die "missing required file: ${path}"
}

require_dir() {
  local path="$1"
  [[ -d "${path}" ]] || die "missing required directory: ${path}"
}

clean_firesim_runs_dir() {
  local dir="${FIRESIM_RUNS_DIR}"
  local enabled="${PYTORCH_CHIPYARD_CLEAN_FIRESIM_RUNS_DIR:-1}"

  [[ "${enabled}" == "1" ]] || return 0
  [[ -n "${dir}" && "${dir}" != "/" ]] || die "refusing to clean unsafe FIRESIM_RUNS_DIR='${dir}'"
  mkdir -p "${dir}"
  find "${dir}" -mindepth 1 -maxdepth 1 -exec rm -rf -- {} +
  log "cleaned FIRESIM_RUNS_DIR: ${dir}"
}

clean_completed_firesim_run() {
  local keep_runfarm="${PYTORCH_CHIPYARD_KEEP_RUNFARM:-${KEEP_RUNFARM:-0}}"

  if [[ "${keep_runfarm}" == "1" ]]; then
    log "preserving FIRESIM_RUNS_DIR because the run farm was kept"
    return 0
  fi
  clean_firesim_runs_dir
}

clean_dir_contents() {
  local label="$1"
  local dir="$2"

  [[ -n "${dir}" && "${dir}" != "/" ]] || die "refusing to clean unsafe ${label}='${dir}'"
  mkdir -p "${dir}"
  find "${dir}" -mindepth 1 -maxdepth 1 -exec rm -rf -- {} +
  log "cleaned ${label}: ${dir}"
}

clean_collected_results() {
  mkdir -p "${PYTORCH_CHIPYARD_FIGURE_RESULTS_WORKLOAD_DIR}"
  log "preserving durable model.log/autotune.log results"
}

yaml_quote() {
  local value="$1"
  value="${value//\\/\\\\}"
  value="${value//\"/\\\"}"
  printf '"%s"' "${value}"
}

split_workload_arg() {
  local value="$1"
  local item
  local -a items

  IFS=, read -r -a items <<<"${value}"
  for item in "${items[@]}"; do
    [[ -n "${item}" ]] || continue
    validate_name "workload" "${item}"
    SELECTED_WORKLOADS+=("${item}")
  done
}

discover_workloads() {
  local json path base workload

  [[ -d "${PYTORCH_CHIPYARD_WORKLOAD_DIR}" ]] || return 0
  while IFS= read -r path; do
    base="$(basename "${path}")"
    workload="${base%.json}"
    case "${workload}" in
      br-base | *base)
        continue
        ;;
    esac
    validate_name "workload" "${workload}"
    printf '%s\n' "${workload}"
  done < <(find "${PYTORCH_CHIPYARD_WORKLOAD_DIR}" -maxdepth 1 -type f -name '*.json' -print | sort -V)
}

unique_workloads() {
  local -A seen=()
  local workload

  for workload in "$@"; do
    [[ -n "${seen[${workload}]:-}" ]] && continue
    seen["${workload}"]=1
    printf '%s\n' "${workload}"
  done
}

elf_has_openmp_symbols() {
  local elf_path="$1"

  LC_ALL=C readelf -Ws "${elf_path}" 2>/dev/null | awk '
    NF >= 8 {
      name = $8
      if (name ~ /^(GOMP_|omp_)/ || name ~ /_omp_fn/) found = 1
    }
    END { exit(found ? 0 : 1) }
  '
}

require_boom_flex_kernel_package() {
  local workload="$1"
  local runner image elf bootbinary workload_json linux_config

  case "${workload}" in
    opt-boom-gemmini-flash-*tok-1core | opt-boom-gemmini-window-*tok-1core) ;;
    *) return 0 ;;
  esac

  runner="${PYTORCH_CHIPYARD_WORKLOAD_DIR}/overlay-${workload}/root/llm/run_${workload}.sh"
  elf="${PYTORCH_CHIPYARD_WORKLOAD_DIR}/overlay-${workload}/root/llm/${workload}/model-1core.elf"
  image="${FIREMARSHAL_IMAGE_DIR}/${workload}/${workload}.img"
  bootbinary="${FIREMARSHAL_IMAGE_DIR}/${workload}/${workload}-bin"
  workload_json="${PYTORCH_CHIPYARD_WORKLOAD_DIR}/${workload}.json"
  linux_config="${PYTORCH_CHIPYARD_WORKLOAD_DIR}/.pytorch-chipyard-${workload}-linux-config"
  require_file "${runner}"
  grep -Fq -- '--kernel-only=flex_attention' "${runner}" || \
    die "${workload} was packaged for full-model execution; rerun Stage 2 to regenerate its ELF, package, and image"
  grep -Fq -- '[runner] openmp=disabled' "${runner}" || \
    die "${workload} runner does not disable OpenMP; rebuild its ELF and repackage the workload"
  if grep -Eq 'OMP_|GOMP_' "${runner}"; then
    die "${workload} runner still configures OpenMP; repackage the workload"
  fi
  command -v readelf >/dev/null 2>&1 || \
    die "readelf is required to verify the ${workload} ELF"
  require_file "${elf}"
  if elf_has_openmp_symbols "${elf}"; then
    die "${workload} ELF still contains OpenMP code; rebuild it with the Spike executable option"
  fi
  if LC_ALL=C readelf -d "${elf}" 2>/dev/null | grep -Fqi 'libgomp'; then
    die "${workload} ELF still links libgomp; rebuild it with the Spike executable option"
  fi
  require_file "${workload_json}"
  require_file "${linux_config}"
  grep -Fq 'CONFIG_CMDLINE="maxcpus=1 console=ttySIF0,3686400 earlycon"' "${linux_config}" || \
    die "${workload} Linux config does not keep BOOM hart 1 offline; repackage the workload"
  grep -Fq "\"config\": \"$(basename "${linux_config}")\"" "${workload_json}" || \
    die "${workload} workload JSON does not reference its maxcpus=1 Linux config; repackage the workload"
  require_file "${image}"
  require_file "${bootbinary}"
  LC_ALL=C grep -aFq 'maxcpus=1 console=ttySIF0,3686400 earlycon' "${bootbinary}" || \
    die "${workload} boot binary was not built with maxcpus=1; rebuild its FireMarshal image"
  [[ "${image}" -nt "${runner}" ]] || \
    die "${workload} FireMarshal image predates its kernel-only runner; rebuild the image before FireSim execution"
}

load_workloads() {
  local workloads=()

  if [[ "${#SELECTED_WORKLOADS[@]}" -gt 0 ]]; then
    mapfile -t workloads < <(unique_workloads "${SELECTED_WORKLOADS[@]}")
  else
    mapfile -t workloads < <(discover_workloads)
  fi

  [[ "${#workloads[@]}" -gt 0 ]] || \
    die "no packaged workloads found under ${PYTORCH_CHIPYARD_WORKLOAD_DIR}; run scripts/package-firemarshal-workload.sh first"

  WORKLOADS=("${workloads[@]}")
}

require_installed_workload_image() {
  local workload="$1"
  local image_dir="${FIREMARSHAL_IMAGE_DIR}/${workload}"

  [[ -s "${image_dir}/${workload}.img" ]] || \
    die "${workload} FireMarshal image is missing: ${image_dir}/${workload}.img; build this workload image before FireSim execution"
  [[ -s "${image_dir}/${workload}-bin" ]] || \
    die "${workload} FireMarshal boot binary is missing: ${image_dir}/${workload}-bin; build this workload image before FireSim execution"
}

apply_resume_filters() {
  local workload
  local found=0
  local filtered=()
  local pending=()

  if [[ -n "${RESUME_FROM}" ]]; then
    for workload in "${WORKLOADS[@]}"; do
      if [[ "${workload}" == "${RESUME_FROM}" ]]; then
        found=1
      fi
      if [[ "${found}" -eq 1 ]]; then
        filtered+=("${workload}")
      fi
    done

    [[ "${found}" -eq 1 ]] || \
      die "resume workload '${RESUME_FROM}' was not found in the selected/discovered workload list"

    WORKLOADS=("${filtered[@]}")
    log "resume-from ${RESUME_FROM}: ${#WORKLOADS[@]} workload(s) remaining"
  fi

  if [[ "${RESUME_MODE}" -eq 1 ]]; then
    for workload in "${WORKLOADS[@]}"; do
      if collected_result_complete "${workload}"; then
        log "resume: skipping completed workload ${workload}"
      else
        pending+=("${workload}")
      fi
    done

    WORKLOADS=("${pending[@]}")
    if [[ "${#WORKLOADS[@]}" -eq 0 ]]; then
      log "resume: no pending workloads"
      return 0
    fi
    log "resume: ${#WORKLOADS[@]} pending workload(s)"
  fi
}

validate_pending_workload_packages() {
  local workload

  [[ "${PREFLIGHT_ONLY}" != "1" ]] || return 0
  for workload in "${WORKLOADS[@]}"; do
    require_file "${PYTORCH_CHIPYARD_WORKLOAD_DIR}/${workload}.json"
    require_file "${FIRESIM_WORKLOAD_DIR}/${workload}.json"
    require_installed_workload_image "${workload}"
    require_boom_flex_kernel_package "${workload}"
  done
}

core_for_workload() {
  local workload="$1"

  if [[ "${workload}" =~ (^|-)([0-9]+)core($|-) ]]; then
    printf '%s\n' "${BASH_REMATCH[2]}"
    return 0
  fi

  return 1
}

is_llm_workload() {
  local workload="$1"

  case "${workload}" in
    gpt2-* | gpt-neo-* | opt-* | pythia-* | *tok*)
      return 0
      ;;
    *)
      return 1
      ;;
  esac
}

should_collect_output_bin() {
  local workload="$1"

  if is_llm_workload "${workload}"; then
    return 1
  fi

  return 0
}

collected_result_dir() {
  local workload="$1"

  printf '%s/%s\n' "${PYTORCH_CHIPYARD_FIGURE_RESULTS_WORKLOAD_DIR}" "${workload}"
}

collected_result_complete() {
  local workload="$1"
  pc_stage2_result_complete \
    "${PYTORCH_CHIPYARD_FIGURE_RESULTS_WORKLOAD_DIR}" "${workload}"
}

contains_tag() {
  local workload="$1"
  local tag="$2"

  case "-${workload}-" in
    *-"${tag}"-*)
      return 0
      ;;
    *)
      return 1
      ;;
  esac
}

env_suffix_for_workload() {
  local workload="$1"
  local suffix

  suffix="${workload^^}"
  suffix="${suffix//[^A-Z0-9_]/_}"
  printf '%s\n' "${suffix}"
}

override_hw_config_for() {
  local workload="$1"
  local suffix var_name overrides pair key value

  suffix="$(env_suffix_for_workload "${workload}")"
  var_name="PYTORCH_CHIPYARD_FIRESIM_HW_CONFIG_${suffix}"
  if [[ -n "${!var_name:-}" ]]; then
    printf '%s\n' "${!var_name}"
    return 0
  fi

  overrides="${PYTORCH_CHIPYARD_FIRESIM_HW_CONFIG_OVERRIDES:-}"
  [[ -n "${overrides}" ]] || return 1

  IFS=, read -r -a pairs <<<"${overrides}"
  for pair in "${pairs[@]}"; do
    key="${pair%%=*}"
    value="${pair#*=}"
    [[ "${key}" == "${workload}" && "${value}" != "${pair}" && -n "${value}" ]] || continue
    printf '%s\n' "${value}"
    return 0
  done

  return 1
}

required_hw_config_for() {
  local workload="$1"

  case "${workload}" in
    opt-boom-gemmini-flash-*tok-1core | opt-boom-gemmini-window-*tok-1core)
      printf '%s\n' "alveo_u250_firesim_fp8x8_gemmini_boom_2core_no_nic"
      ;;
    alexnet-rvv-2core | squeezenet-rvv-2core)
      printf '%s\n' "alveo_u250_firesim_minv128d64_rocket_2core_no_nic"
      ;;
    mobilenetv2-rvv-2core | resnet50-rvv-2core)
      printf '%s\n' "alveo_u250_firesim_minv128d64_rocket_4core_no_nic_30mhz"
      ;;
    squeezenet-rvv-4core)
      printf '%s\n' "alveo_u250_firesim_minv128d64_rocket_4core_no_nic_30mhz"
      ;;
    alexnet-rvv-4core | mobilenetv2-rvv-4core | resnet50-rvv-4core)
      printf '%s\n' "alveo_u250_firesim_minv128d64_rocket_8core_no_nic_30mhz"
      ;;
    *)
      return 1
      ;;
  esac
}

rvv_success_profile_for() {
  local workload="$1"

  case "${workload}" in
    smoke-gemm-rvv-4core)
      printf '%s\n' '{0},{1},{2},{3}|0 1 2 3|ACTIVE|INFINITE|0|'
      ;;
    alexnet-rvv-2core)
      printf '%s\n' '{0},{1}|0 1|ACTIVE|INFINITE|0|'
      ;;
    alexnet-rvv-4core)
      printf '%s\n' '{4},{5},{6},{7}|4 5 6 7|ACTIVE|INFINITE|1|4-7'
      ;;
    mobilenetv2-rvv-2core)
      printf '%s\n' '{2},{3}|2 3|ACTIVE|INFINITE|0|'
      ;;
    mobilenetv2-rvv-4core)
      printf '%s\n' '{0},{1},{6},{7}|0 1 6 7|ACTIVE|INFINITE|1|0-1,6-7'
      ;;
    resnet50-rvv-2core)
      printf '%s\n' '{0},{1}|0 1|ACTIVE|INFINITE|1|0-1'
      ;;
    resnet50-rvv-4core)
      printf '%s\n' '{4},{5},{6},{7}|4 5 6 7|ACTIVE|INFINITE|1|4-7'
      ;;
    squeezenet-rvv-2core)
      printf '%s\n' '{0},{1}|0 1|ACTIVE|INFINITE|0|'
      ;;
    squeezenet-rvv-4core)
      printf '%s\n' '{0},{1},{2},{3}|0 1 2 3|PASSIVE|0|0|'
      ;;
    *)
      return 1
      ;;
  esac
}

validate_rvv_success_package() {
  local workload="$1"
  local profile expected_places expected_affinity expected_wait expected_spin
  local requires_hz100 expected_worker runner workload_json linux_fragment
  local linux_config image bootbinary

  contains_tag "${workload}" "rvv" || return 0

  profile="$(rvv_success_profile_for "${workload}")" || \
    die "${workload} has no validated RVV success profile"
  IFS='|' read -r expected_places expected_affinity expected_wait expected_spin \
    requires_hz100 expected_worker <<<"${profile}"

  runner="$(find "${PYTORCH_CHIPYARD_WORKLOAD_DIR}/overlay-${workload}" \
    -type f -name "run_${workload}.sh" -print -quit 2>/dev/null || true)"
  workload_json="${PYTORCH_CHIPYARD_WORKLOAD_DIR}/${workload}.json"
  linux_fragment="${PYTORCH_CHIPYARD_WORKLOAD_DIR}/.pytorch-chipyard-${workload}-linux-config"
  linux_config="${FIREMARSHAL_IMAGE_DIR}/${workload}/linux_config"
  image="${FIREMARSHAL_IMAGE_DIR}/${workload}/${workload}.img"
  bootbinary="${FIREMARSHAL_IMAGE_DIR}/${workload}/${workload}-bin"

  [[ -n "${runner}" ]] || \
    die "${workload} packaged runner is missing; rerun package-firemarshal-workload.sh"
  require_file "${workload_json}"
  require_file "${image}"
  require_file "${bootbinary}"

  grep -Fqx "export OMP_PLACES=\"${expected_places}\"" "${runner}" || \
    die "${workload} runner does not use validated OMP_PLACES=${expected_places}; repackage and rebuild it"
  grep -Fqx "export GOMP_CPU_AFFINITY=\"${expected_affinity}\"" "${runner}" || \
    die "${workload} runner does not use validated GOMP_CPU_AFFINITY=${expected_affinity}; repackage and rebuild it"
  grep -Fqx "export OMP_WAIT_POLICY=${expected_wait}" "${runner}" || \
    die "${workload} runner does not use validated OMP_WAIT_POLICY=${expected_wait}; repackage and rebuild it"
  grep -Fqx "export GOMP_SPINCOUNT=${expected_spin}" "${runner}" || \
    die "${workload} runner does not use validated GOMP_SPINCOUNT=${expected_spin}; repackage and rebuild it"

  if [[ "${requires_hz100}" == "1" ]]; then
    require_file "${linux_fragment}"
    require_file "${linux_config}"
    grep -Fq "\"linux\": {\"config\": \"$(basename "${linux_fragment}")\"}" "${workload_json}" || \
      die "${workload} FireMarshal JSON does not select its stable Linux fragment; repackage and rebuild it"
    grep -Fqx 'CONFIG_HZ=100' "${linux_config}" || \
      die "${workload} boot binary was not built with CONFIG_HZ=100; rebuild its FireMarshal image"
    grep -Fqx 'CONFIG_NO_HZ_FULL=y' "${linux_config}" || \
      die "${workload} boot binary was not built with CONFIG_NO_HZ_FULL=y; rebuild its FireMarshal image"
    grep -Fq "nohz_full=${expected_worker}" "${linux_config}" || \
      die "${workload} kernel command line does not isolate workers ${expected_worker}; rebuild its FireMarshal image"
    grep -Fq '[runner] rvv_stable_profile=hz100-nohz-full-fifo-v1' "${runner}" || \
      die "${workload} runner is missing the validated RVV runtime tuning; repackage and rebuild it"
    grep -Fq "taskset -c ${expected_worker} chrt -f 1 ./model-" "${runner}" || \
      die "${workload} runner is missing taskset/SCHED_FIFO for workers ${expected_worker}; repackage and rebuild it"
    grep -Fq 'sysctl -w kernel.sched_rt_runtime_us=-1' "${runner}" || \
      die "${workload} runner does not disable RT throttling; repackage and rebuild it"
  fi
}

infer_hw_config() {
  local workload="$1"
  local core override required

  if required="$(required_hw_config_for "${workload}")"; then
    if override="$(override_hw_config_for "${workload}")" && \
        [[ "${override}" != "${required}" ]]; then
      die "${workload} requires hardware config '${required}', but an environment override selected '${override}'"
    fi
    printf '%s\n' "${required}"
    return 0
  fi

  if override_hw_config_for "${workload}"; then
    return 0
  fi

  core="$(core_for_workload "${workload}")" || \
    die "could not infer core count from workload '${workload}'"

  if contains_tag "${workload}" "boom"; then
    case "${core}" in
      1) printf '%s\n' "alveo_u250_firesim_fp8x8_gemmini_boom_2core_no_nic" ;;
      2) printf '%s\n' "alveo_u250_firesim_fp8x8_gemmini_boom_2core_no_nic" ;;
      4) printf '%s\n' "alveo_u250_firesim_fp8x8_gemmini_boom_4core_no_nic" ;;
      *) die "no BOOM hardware config mapping for ${workload}" ;;
    esac
  elif contains_tag "${workload}" "gemmini"; then
    case "${core}" in
      2) printf '%s\n' "alveo_u250_firesim_fp8x8_gemmini_rocket_2core_no_nic" ;;
      4) printf '%s\n' "alveo_u250_firesim_fp8x8_gemmini_rocket_4core_no_nic" ;;
      *) die "no Gemmini hardware config mapping for ${workload}" ;;
    esac
  elif contains_tag "${workload}" "rvv"; then
    case "${core}" in
      1) printf '%s\n' "alveo_u250_firesim_minv128d64_rocket_4core_no_nic" ;;
      2)
        if [[ "${workload}" == "mobilenetv2-rvv-2core" ]]; then
          printf '%s\n' "alveo_u250_firesim_minv128d64_rocket_4core_no_nic_30mhz"
        else
          printf '%s\n' "alveo_u250_firesim_minv128d64_rocket_2core_no_nic"
        fi
        ;;
      4)
        printf '%s\n' "alveo_u250_firesim_minv128d64_rocket_8core_no_nic_30mhz"
        ;;
      *) die "no RVV hardware config mapping for ${workload}" ;;
    esac
  elif contains_tag "${workload}" "rocket"; then
    printf '%s\n' "alveo_u250_firesim_rocket_16core_no_nic"
  elif contains_tag "${workload}" "scalar"; then
    printf '%s\n' "alveo_u250_firesim_rocket_16core_no_nic"
  elif is_llm_workload "${workload}"; then
    case "${core}" in
      2) printf '%s\n' "alveo_u250_firesim_fp8x8_gemmini_rocket_2core_no_nic" ;;
      4) printf '%s\n' "alveo_u250_firesim_rocket_16core_no_nic" ;;
      *) die "no LLM fallback hardware config mapping for ${workload}" ;;
    esac
  elif [[ "${core}" == "16" ]]; then
    printf '%s\n' "alveo_u250_firesim_rocket_16core_no_nic"
  else
    die "could not infer hardware config for workload '${workload}'; set PYTORCH_CHIPYARD_FIRESIM_HW_CONFIG_$(env_suffix_for_workload "${workload}")"
  fi
}

validate_required_hw_config() {
  local workload="$1"
  local hw_config="$2"
  local required

  required="$(required_hw_config_for "${workload}")" || return 0
  [[ "${hw_config}" == "${required}" ]] || \
    die "${workload} must use hardware config '${required}', got '${hw_config}'"
}

require_hw_config() {
  local hw_config="$1"
  local validator="${SCRIPT_DIR}/validate-firesim-hwdb.py"

  require_file "${FIRESIM_HWDB_PATH}"
  require_file "${FIRESIM_BUILD_RECIPES_PATH}"
  require_file "${validator}"

  "${FIRESIM_PYTHON}" "${validator}" \
    --hwdb "${FIRESIM_HWDB_PATH}" \
    --config "${hw_config}" || \
    die "hardware artifact preflight failed for '${hw_config}'"
}

resolve_firesim_python() {
  local chipyard_python="${CHIPYARD_DIR}/.conda-env/bin/python3"
  local python_bin="${PYTORCH_CHIPYARD_FIRESIM_PYTHON:-${chipyard_python}}"

  [[ -x "${python_bin}" ]] || \
